"""Independent finite oracle: squared side lengths + shoelace determinant.
No production vector/dot helpers are used to derive expected answers.
All checks remain active under python -O/-OO.
"""
from fractions import Fraction as F
from itertools import product
from collections import Counter
import sys
from geometry import verify

counts = Counter()
def require(ok, message):
    if not ok: raise AssertionError(message)
def sq(P,Q):
    return sum((F(x)-F(y))**2 for x,y in zip(P,Q))
def area2(A,B,C):
    return A[0]*B[1]+B[0]*C[1]+C[0]*A[1]-A[1]*B[0]-B[1]*C[0]-C[1]*A[0]
def check(A,B,C):
    a,b,c=sq(B,C),sq(A,C),sq(A,B)
    cross=area2(A,B,C)
    valid=cross != 0 and a+c>b
    acute=valid and a+b>c and b+c>a
    try: r=verify(A,B,C)
    except ValueError:
        require(not valid,('false rejection',A,B,C)); counts['grid_rejected']+=1
        return
    require(valid,('false acceptance',A,B,C)); counts['grid_accepted']+=1
    delta=a+c-b
    expected_t=delta/(2*a)
    expected_case='interior' if delta<2*a else ('at-C' if delta==2*a else 'beyond-C')
    require((r['bc2'],r['ac2'],r['ba2'])==(a,b,c),'side squares')
    require(r['twice_rectangle']==delta and r['rectangle']==delta/2,'independent deficit')
    require(r['t']==expected_t and r['case']==expected_case,'position')
    require(r['all_acute']==acute and r['domain']==('original-domain' if acute else 'modern-extension'),'domain')
    D=r['D']
    require(area2(B,C,D)==0,'foot on baseline')
    # Area of ABC and base length independently determine altitude squared.
    h2=F(cross)**2/a
    require(sq(A,D)==h2 and r['ad2']==h2,'altitude from area')
    require(sq(B,D)==delta**2/(4*a) and r['bd2']==sq(B,D),'foot distance')
    require(sq(C,D)==(2*a-delta)**2/(4*a) and r['dc2']==sq(C,D),'other foot distance')
    require(c==h2+sq(B,D) and b==h2+sq(C,D),'two right triangles')
    require(r['rectangle']**2==a*sq(B,D) and r['rectangle']>0,'positive rectangle product')
    require(r['lhs']==a+c and r['rhs']==a+c,'identity')
    require(all(type(r[k]) is F for k in ['bc2','ba2','ac2','t','rectangle','ad2']),'exact rational return')
    try: strict=verify(A,B,C,original_only=True)
    except ValueError: require(not acute,'strict false rejection')
    else: require(acute and strict==r,'strict false acceptance')

points=list(product(range(-3,4),repeat=2))
for A,C in product(points,repeat=2): check(A,(0,0),C)
print('INTEGER_GRID',dict(counts),'total',len(points)**2)
# Rational similarities and nonsimilarity affine maps. For the latter we
# recompute domain rather than assume angles survive shear.
base=[((2,4),(0,0),(5,0)),((2,1),(0,0),(5,0)),((5,3),(0,0),(5,0)),((7,3),(0,0),(5,0)),((0,4),(0,0),(5,0)),((-2,4),(0,0),(5,0)),((2,2),(0,0),(4,0)),((2,0),(0,0),(5,0))]
matrices=[(F(3,5),F(-4,5),F(4,5),F(3,5)),(1,F(2,3),F(-1,4),1),(0,1,1,0)]
before=sum(counts.values()); transformed=0
for tri,m,s,shift in product(base,matrices,[F(2,3),F(-7,11),F(10**30,7)],[(F(1,3),F(-2,7)),(F(-100,9),F(17,13))]):
    p,q,r,t=m
    def f(P): return (s*(p*P[0]+q*P[1])+shift[0],s*(r*P[0]+t*P[1])+shift[1])
    check(*(f(P) for P in tri)); transformed+=1
print('RATIONAL_TRANSFORMS',transformed)
# Hand certificates, not generated by production.
certificates=[((2,4),(0,0),(5,0),(25,20,25,20,45,'original-domain','interior')),
 ((2,1),(0,0),(5,0),(25,5,10,20,30,'modern-extension','interior')),
 ((5,3),(0,0),(5,0),(25,34,9,50,59,'modern-extension','at-C')),
 ((7,3),(0,0),(5,0),(25,58,13,70,83,'modern-extension','beyond-C')),
 ((2,2),(0,0),(4,0),(16,8,8,16,24,'modern-extension','interior')),
 ((0,2),(0,0),(1,1),(2,4,2,4,6,'modern-extension','at-C'))]
for A,B,C,expected in certificates:
    r=verify(A,B,C)
    require(tuple(r[k] for k in ['bc2','ba2','ac2','twice_rectangle','lhs','domain','case'])==expected,'hand certificate')
print('HAND_CERTIFICATES',len(certificates))
for n in [18,30,100]:
    eps=F(1,10**n)
    for x in [eps,5-eps,5,5+eps]: check((x,4),(0,0),(5,0))
print('EXACT_BOUNDARIES',12)
bad_values=[True,False,2.0,complex(2), '2',None,[],{},F] 
bad_points=[None,'24',(2,),(2,4,6),{},set([2,4]),iter([2,4])]
invalid=0
for loc in range(3):
    for bad in [(x,4) for x in bad_values]+[(2,x) for x in bad_values]+bad_points:
        tri=[(2,4),(0,0),(5,0)]; tri[loc]=bad
        try: verify(*tri)
        except TypeError: invalid+=1
        else: raise AssertionError(('accepted malformed point',loc,bad))
for flag in [0,1,None,'true',[],F(1)]:
    try: verify((2,4),(0,0),(5,0),original_only=flag)
    except TypeError: invalid+=1
    else: raise AssertionError('invalid strict flag accepted')
print('INVALID_TYPES',invalid)
print('PASS independent exact checks; optimize=',sys.flags.optimize)
