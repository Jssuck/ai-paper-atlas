import unittest
from fractions import Fraction as Q
from geometry import *
class GeometryTests(unittest.TestCase):
 def setUp(self):self.a=Circle((0,0),5);self.b=Circle((3,0),2)
 def test_01_contact(self):self.assertEqual(verify_contact(self.a,self.b,(5,0))['cross'],0)
 def test_02_candidate(self):self.assertEqual(contact_candidate(self.a,self.b),(5,0))
 def test_03_internal(self):self.assertEqual(relation(self.a,self.b),'internal_tangent')
 def test_04_external(self):self.assertEqual(relation(self.a,Circle((7,0),2)),'external_tangent')
 def test_05_secant(self):self.assertEqual(relation(self.a,Circle((4,0),2)),'secant')
 def test_06_separate(self):self.assertEqual(relation(self.a,Circle((8,0),2)),'separate')
 def test_07_nested(self):self.assertEqual(relation(self.a,Circle((1,0),2)),'strictly_nested')
 def test_08_concentric(self):self.assertEqual(relation(self.a,Circle((0,0),2)),'concentric_disjoint')
 def test_09_coincident(self):self.assertEqual(relation(self.a,self.a),'coincident')
 def test_10_zero(self):self.assertRaises(ValueError,Circle,(0,0),0)
 def test_11_negative(self):self.assertRaises(ValueError,Circle,(0,0),-1)
 def test_12_float(self):self.assertRaises(TypeError,Circle,(0.0,0),1)
 def test_13_bool(self):self.assertRaises(TypeError,Circle,(0,0),True)
 def test_14_shape(self):self.assertRaises(ValueError,Circle,(0,),1)
 def test_15_wrong_point(self):self.assertRaises(ValueError,verify_contact,self.a,self.b,(0,5))
 def test_16_opposite(self):self.assertRaises(ValueError,verify_contact,self.a,self.b,(-5,0))
 def test_17_reversed(self):self.assertRaises(ValueError,verify_contact,self.b,self.a,(5,0))
 def test_18_equal_radius(self):self.assertRaises(ValueError,verify_contact,self.a,self.a,(5,0))
 def test_19_external_rejected(self):self.assertRaises(ValueError,verify_contact,self.a,Circle((7,0),2),(5,0))
 def test_20_secant_rejected(self):self.assertRaises(ValueError,verify_contact,self.a,Circle((6,0),5),(3,4))
 def test_21_containment(self):self.assertTrue(closed_disk_inside(self.a,self.b));self.assertFalse(closed_disk_inside(self.b,self.a))
 def test_22_symmetric_relation(self):self.assertEqual(relation(self.a,self.b),relation(self.b,self.a))
 def test_23_rotated(self):self.assertEqual(contact_candidate(Circle((2,-3),5),Circle((Q(19,5),Q(-3,5)),2)),(5,1))
 def test_24_grid(self):self.assertEqual(grid(),600)
 def test_25_candidate_rejects(self):self.assertRaises(ValueError,contact_candidate,self.a,Circle((4,0),2))
 def test_26_no_epsilon(self):self.assertEqual(relation(self.a,Circle((3+Q(1,10**50),0),2)),'secant')
if __name__=='__main__':unittest.main(verbosity=2)
