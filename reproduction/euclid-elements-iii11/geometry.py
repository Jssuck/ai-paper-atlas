"""Exact rational teaching model for III.11, not a Euclidean proof assistant."""
from dataclasses import dataclass
from fractions import Fraction as Q

def rational(x):
    if isinstance(x,bool) or not isinstance(x,(int,Q)):
        raise TypeError('only int and Fraction are accepted')
    return Q(x)

def point(p):
    if not isinstance(p,(tuple,list)) or len(p)!=2: raise ValueError('point needs two coordinates')
    return tuple(rational(x) for x in p)

def sub(a,b): return tuple(x-y for x,y in zip(a,b))
def dot(a,b): return sum(x*y for x,y in zip(a,b))
def cross(a,b): return a[0]*b[1]-a[1]*b[0]
def distance2(a,b):
    v=sub(point(a),point(b));return dot(v,v)

@dataclass(frozen=True)
class Circle:
    center: tuple
    radius: Q
    def __post_init__(self):
        object.__setattr__(self,'center',point(self.center))
        object.__setattr__(self,'radius',rational(self.radius))
        if self.radius<=0: raise ValueError('positive radius required')
    def contains_boundary(self,p): return distance2(self.center,p)==self.radius**2

def relation(a,b):
    """Symmetric classification using squared distances; no square roots/tolerances."""
    d2=distance2(a.center,b.center); lo=(a.radius-b.radius)**2; hi=(a.radius+b.radius)**2
    if d2==0: return 'coincident' if a.radius==b.radius else 'concentric_disjoint'
    if d2<lo:return 'strictly_nested'
    if d2==lo:return 'internal_tangent'
    if d2<hi:return 'secant'
    if d2==hi:return 'external_tangent'
    return 'separate'

def closed_disk_inside(outer,inner):
    """d+r <= R, squared only after requiring R-r >= 0."""
    gap=outer.radius-inner.radius
    return gap>=0 and distance2(outer.center,inner.center)<=gap*gap

def verify_contact(outer,inner,t):
    """Input premises: strict radii order, disk inclusion, supplied common boundary point.
    Collinearity, side and metric tangency are conclusions checked independently.
    No candidate is generated by this checker.
    """
    t=point(t)
    if outer.radius<=inner.radius: raise ValueError('outer radius must be strictly greater')
    if not closed_disk_inside(outer,inner):raise ValueError('inner disk not contained')
    if not outer.contains_boundary(t) or not inner.contains_boundary(t):raise ValueError('not a common boundary point')
    v=sub(inner.center,outer.center); w=sub(t,outer.center)
    c=cross(v,w); s=dot(v,w); gap=outer.radius-inner.radius
    metric=distance2(outer.center,inner.center)==gap*gap
    beyond=dot(sub(t,inner.center),v)>0
    if not (metric and c==0 and s>0 and beyond): raise ArithmeticError('III.11 conclusion failed')
    return {'common_boundary':True,'disk_inclusion':True,'center_distance2':distance2(outer.center,inner.center),
            'radius_gap2':gap*gap,'cross':c,'forward_dot':s,'beyond_inner_center':beyond}

def contact_candidate(outer,inner):
    """Modern rational construction, kept separate from premise-based checker."""
    if outer.radius<=inner.radius or relation(outer,inner)!='internal_tangent': raise ValueError('ordered internal tangent pair required')
    gap=outer.radius-inner.radius
    return tuple(o+outer.radius*(c-o)/gap for o,c in zip(outer.center,inner.center))

def grid():
    """600 exact translated/rotated/scaled internal-tangent certificates."""
    directions=[(Q(1),Q(0)),(Q(0),Q(1)),(Q(-1),Q(0)),(Q(3,5),Q(4,5)),(Q(-5,13),Q(12,13))]
    count=0
    for shift in [(0,0),(2,-3),(-7,5),(Q(1,3),Q(-2,7))]:
      for u in directions:
       for r in [Q(1,2),Q(1),Q(3)]:
        for gap in [Q(i,3) for i in range(1,11)]:
         # Supply point directly by independent geometric parametrization.
         R=r+gap; outer=Circle(shift,R); inner=Circle(tuple(shift[i]+gap*u[i] for i in range(2)),r)
         t=tuple(shift[i]+R*u[i] for i in range(2))
         verify_contact(outer,inner,t)
         if contact_candidate(outer,inner)!=t:raise ArithmeticError('candidate mismatch')
         count+=1
    return count
