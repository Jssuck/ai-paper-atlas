import unittest
from fractions import Fraction as F
from geometry import *
class Tests(unittest.TestCase):
 def setUp(self):self.a=((0,0),(3,4),5,(-4,3),(-3,-4))
 def test_inward(self):self.assertEqual(certify(*self.a)['t'],1)
 def test_outward(self):self.assertEqual(certify(*self.a[:-1],(3,4))['t'],-1)
 def test_ray(self):self.assertFalse(certify(*self.a[:-1],(3,4))['ray_reaches_centre'])
 def test_normal_scaled(self):self.assertEqual(certify(*self.a[:-1],(-6,-8))['t'],F(1,2))
 def test_tangent_reversed(self):self.assertTrue(verify(*self.a[:3],(4,-3),self.a[4],certify(*self.a)))
 def test_translate(self):self.assertEqual(certify((2,-1),(5,3),5,(-4,3),(-3,-4))['centre_on_line'],(2,-1))
 def test_rotate(self):self.assertEqual(certify((0,0),(-4,3),5,(-3,-4),(4,-3))['t'],1)
 def test_fraction(self):self.assertTrue(verify((0,0),(F(3,5),F(4,5)),1,(-4,3),(-3,-4),certify((0,0),(F(3,5),F(4,5)),1,(-4,3),(-3,-4))))
 def test_grid(self):self.assertEqual(grid()['configurations'],432)
 def test_zero_radius(self):self.assertRaises(ValueError,certify,(0,0),(0,0),0,(1,0),(0,1))
 def test_negative_radius(self):self.assertRaises(ValueError,certify,*self.a[:2],-5,*self.a[3:])
 def test_off_circle(self):self.assertRaises(ValueError,certify,(0,0),(3,3),5,*self.a[3:])
 def test_zero_tangent(self):self.assertRaises(ValueError,certify,*self.a[:3],(0,0),self.a[4])
 def test_zero_normal(self):self.assertRaises(ValueError,certify,*self.a[:-1],(0,0))
 def test_secant(self):self.assertRaises(ValueError,certify,*self.a[:3],(1,0),(0,1))
 def test_wrong_normal(self):self.assertRaises(ValueError,certify,*self.a[:-1],(1,0))
 def test_bool(self):self.assertRaises(ValueError,certify,*self.a[:2],True,*self.a[3:])
 def test_float(self):self.assertRaises(ValueError,certify,*self.a[:2],5.0,*self.a[3:])
 def test_short_point(self):self.assertRaises(ValueError,certify,(0,),*self.a[1:])
 def test_tamper_parameter(self):c=certify(*self.a);c['t']+=1;self.assertFalse(verify(*self.a,c))
 def test_tamper_centre(self):c=certify(*self.a);c['centre_on_line']=(1,1);self.assertFalse(verify(*self.a,c))
 def test_tamper_power(self):c=certify(*self.a);c['tangent_power_coefficient']+=1;self.assertFalse(verify(*self.a,c))
 def test_tamper_norm(self):c=certify(*self.a);c['normal_norm2']+=1;self.assertFalse(verify(*self.a,c))
 def test_tamper_ray(self):c=certify(*self.a);c['ray_reaches_centre']=False;self.assertFalse(verify(*self.a,c))
 def test_bool_parameter(self):c=certify(*self.a);c['t']=True;self.assertFalse(verify(*self.a,c))
 def test_numeric_ray(self):c=certify(*self.a);c['ray_reaches_centre']=1;self.assertFalse(verify(*self.a,c))
 def test_extra_key(self):c=certify(*self.a);c['extra']=0;self.assertFalse(verify(*self.a,c))
 def test_missing_key(self):c=certify(*self.a);del c['t'];self.assertFalse(verify(*self.a,c))
if __name__=='__main__':unittest.main(verbosity=2)
