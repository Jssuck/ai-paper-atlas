from geometry import *
s=Segment(2,F(3,2)); p=s.arc_point(1)
t=Segment(2,F(3,2),(5,-1),(F(3,5),F(4,5)),(F(4,5),F(-3,5)))
print('exact point:',p,'cot:',s.measured_cot(p))
print('placed endpoints:',t.endpoints,'placed point:',s.align_point_to(t,p))
print('placed center:',s.align_point_to(t,s.center),'target center:',t.center,'radius squared:',t.radius2)
print('before placement coincident:',s.coincides(t),'after placement circle matches:',s.aligned_circle_matches(t))
mirror=Segment(2,F(3,2),n=(0,-1))
print('mirror similar:',s.similar(mirror),'coincident:',s.coincides(mirror),'rigidly matches:',s.aligned_circle_matches(mirror))
other=Segment(2,F(-3,2),n=(0,-1))
print('same circle opposite segment cot:',other.angle_cot,'similar:',s.similar(other))
large=Segment(4,3)
print('scaled similar:',s.similar(large),'base lengths:',2*s.a,2*large.a,'radius squares:',s.radius2,large.radius2)
print('grid:',grid())
